"""Inline the Raseed web app (../raseed/www) into web/bundle.js for the iOS WebView."""
import base64, io, json, os, re, sys
from PIL import Image
WWW = sys.argv[1]; OUT = sys.argv[2]
rd = lambda p: open(os.path.join(WWW, p), encoding='utf-8').read()
b64 = lambda p: base64.b64encode(open(os.path.join(WWW, p), 'rb').read()).decode()
fonts = {w: 'data:font/woff2;base64,' + b64(f'fonts/IBMPlexSansArabic-{w}.woff2') for w in ['Regular', 'Medium', 'SemiBold', 'Bold']}
im = Image.open(os.path.join(WWW, 'img/logo.png')).convert('RGBA').resize((256, 256), Image.LANCZOS)
buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
logo = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
css = rd('css/app.css')
css = re.sub(r'@font-face\{[^}]*\}\s*', '', css, count=4)
head = ("<script>window.__FONTS=" + json.dumps(fonts) + ";window.__LOGO=" + json.dumps(logo) + ";"
        "(function(){var F=window.__FONTS,w={Regular:400,Medium:500,SemiBold:600,Bold:700},c='';"
        "for(var k in w)c+='@font-face{font-family:Plex;src:url('+F[k]+') format(\"woff2\");font-weight:'+w[k]+';font-display:block}';"
        "document.write('<style>'+c+'</style>');})();</script>\n<style>" + css + "</style>")
html = rd('index.html').replace('<link rel="stylesheet" href="css/app.css">', head)
def inline(m):
    src = rd(m.group(1)).replace('</script', '<\\/script')
    return '<script>' + src + '</script>'
html = re.sub(r'<script src="([^"]+)"></script>', inline, html)
assert 'src="js/' not in html and 'href="css/' not in html
os.makedirs(os.path.dirname(OUT), exist_ok=True)
if OUT.endswith('.html'):
    open(OUT, 'w', encoding='utf-8').write(html)
else:
    open(OUT, 'w', encoding='utf-8').write('// generated by scripts/build_bundle.py — do not edit\nexport default ' + json.dumps(html, ensure_ascii=False) + ';\n')
print('bundle', round(len(html) / 1024), 'KB')
